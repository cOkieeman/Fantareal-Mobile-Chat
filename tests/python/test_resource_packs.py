def test_zero_and_insufficient_quota_leave_no_partial_pack(tmp_path: Path) -> None:
    selected = make_pack(tmp_path / "quota-pack")
    zero = initialized_service(tmp_path / "zero", 0)
    inspected = preview(zero, selected)
    assert inspected["fitsQuota"] is False
    with pytest.raises(DomainError) as zero_error:
        install(zero, selected)
    assert zero_error.value.code == "assets_quota_unconfigured"
    assert zero.dispatch("mobile.resources.list", {"context": context()})["packs"] == []

    tiny = initialized_service(tmp_path / "tiny", 8)
    with pytest.raises(DomainError) as tiny_error:
        install(tiny, selected)
    assert tiny_error.value.code == "assets_quota_exceeded"
    assert tiny.dispatch("mobile.resources.list", {"context": context()})["packs"] == []


