def test_failed_replacement_restores_previous_pack(
    service: MobileChatService,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    first = make_pack(tmp_path / "first-pack", version="1.0.0")
    install(service, first)
    second = make_pack(
        tmp_path / "second-pack",
        version="2.0.0",
        payload=png_bytes(180, 70, 130),
    )
    inspected = preview(service, second)

    from fantareal_mobile_chat import resource_packs

    real_replace = resource_packs.os.replace

    def fail_stage(source: Any, destination: Any) -> None:
        if str(source).endswith(".stage"):
            raise OSError("fixture swap failure")
        real_replace(source, destination)

    monkeypatch.setattr(resource_packs.os, "replace", fail_stage)
    with pytest.raises(DomainError) as exc_info:
        service.dispatch(
            "mobile.resources.import",
            {
                "context": context(),
                "directoryToken": TOKEN,
                "contentDigest": inspected["contentDigest"],
            },
        )
    assert exc_info.value.code == "storage_write_failed"
    listed = service.dispatch("mobile.resources.list", {"context": context()})
    assert listed["packs"][0]["version"] == "1.0.0"


def test_damaged_installed_pack_does_not_break_text_chat(
    service: MobileChatService,
    tmp_path: Path,
) -> None:
    selected = make_pack(tmp_path / "damage-after-install")
    install(service, selected)
    assert service.resource_packs is not None
    installed = (
        service.resource_packs.assets_root
        / "cards"
        / "card_a"
        / "resource-packs"
        / "com.example.fixture"
        / "resource-pack.json"
    )
    installed.write_text("{broken", encoding="utf-8")
    listed = service.dispatch("mobile.resources.list", {"context": context()})
    assert listed["packs"][0]["status"] == "damaged"
    assert service.dispatch("mobile.groups.list", {"context": context()}) == {"groups": []}
    assert service.dispatch(
        "mobile.resources.delete",
        {"context": context(), "packId": "com.example.fixture"},
    )["deleted"] is True


def test_appearance_is_per_card_and_background_falls_back_after_delete(
    service: MobileChatService,
    tmp_path: Path,
) -> None:
    selected = make_mixed_pack(tmp_path / "mixed-pack")
    install(service, selected)

    updated = service.dispatch(
        "mobile.appearance.update",
        {
            "context": context(),
            "appearance": {
                "preset": "xianxia",
                "tone": "mist",
                "background": {
                    "packId": "com.example.fixture",
                    "assetId": "night-background",
                },
            },
        },
    )
    assert updated["appearance"]["preset"] == "xianxia"
    assert updated["appearance"]["tone"] == "mist"
    assert updated["backgroundAsset"]["dataUrl"].startswith("data:image/png;base64,")
    catalog = service.dispatch(
        "mobile.resources.assets.list",
        {"context": context(), "kind": "sticker", "offset": 0, "limit": 24},
    )
    assert catalog["total"] == 1
    assert catalog["assets"][0]["packId"] == "com.example.fixture"
    for field, value in (("offset", "later"), ("limit", 2.5), ("limit", True)):
        with pytest.raises(DomainError) as invalid_page:
            service.dispatch(
                "mobile.resources.assets.list",
                {
                    "context": context(),
                    "kind": "sticker",
                    "offset": 0,
                    "limit": 24,
                    field: value,
                },
            )
        assert invalid_page.value.code == "invalid_params"
    resolved = service.dispatch(
        "mobile.resources.asset.get",
        {
            "context": context(),
            "packId": "com.example.fixture",
            "assetId": "rain-sticker",
            "kind": "sticker",
        },
    )
    assert resolved["asset"]["dataUrl"].startswith("data:image/png;base64,")

    bob = character("card_b", "Bob")
    service.dispatch(
        "mobile.context.bind",
        {
            "context": context("card_b", "revision_b"),
            "activeCharacter": bob,
            "characters": [bob],
        },
    )
    assert service.dispatch(
        "mobile.appearance.get",
        {"context": context("card_b", "revision_b")},
    )["appearance"] == {
        "schemaVersion": 1,
        "preset": "modern",
        "tone": "midnight",
        "background": None,
    }

    alice = character()
    service.dispatch(
        "mobile.context.bind",
        {
            "context": context(),
            "activeCharacter": alice,
            "characters": [alice],
        },
    )
    service.dispatch(
        "mobile.resources.delete",
        {"context": context(), "packId": "com.example.fixture"},
    )
    fallback = service.dispatch("mobile.appearance.get", {"context": context()})
    assert fallback["appearance"]["background"] is None
    assert fallback["fallback"] == "background_missing"
